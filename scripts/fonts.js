// Self-hosted web fonts (#91): no request goes to Google Fonts. Copies the DESIGN.md fonts
// from the @fontsource-variable packages (SIL OFL 1.1) into src/fonts/ (committed) and writes
// src/fonts/fonts.css, the @font-face rules. Run it after upgrading those packages:
//   node scripts/fonts.js [outDir]
// Only what the site uses: Newsreader roman + italic with the opsz and wght axes, Source Sans 3
// roman (wght; the site sets no sans italic). Subsets: latin, latin-ext and vietnamese (author
// names like "Nguyễn" need it) plus greek for Source Sans 3 (abstracts use α, β; Newsreader has
// no greek). unicode-range means a browser only downloads the subsets a page actually renders.
// The head links fonts.css, so Framework copies it to _file/fonts/fonts.<hash>.css; its url()s
// point next to it, and scripts/copyStatic.js copies the .woff2 to dist/_file/fonts/.
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

export const FONTS = [
  {
    pkg: "@fontsource-variable/newsreader",
    family: "Newsreader",
    css: ["opsz.css", "opsz-italic.css"],
    subsets: ["latin", "latin-ext", "vietnamese"],
  },
  {
    pkg: "@fontsource-variable/source-sans-3",
    family: "Source Sans 3",
    css: ["wght.css"],
    subsets: ["latin", "latin-ext", "greek", "vietnamese"],
  },
];

/**
 * Keeps the @font-face rules of a fontsource stylesheet whose subset is wanted, renamed to
 * `family` ("Newsreader Variable" → "Newsreader", the name DESIGN.md's tokens use) and pointing
 * at the bare file name. Returns { css, files }.
 */
export function selectFaces(source, { pkg, family, subsets }) {
  const name = pkg.split("/").pop();
  const rules = [];
  const files = [];
  for (const [, label, body] of source.matchAll(
    /\/\* ([\w-]+) \*\/\s*@font-face\s*\{([^}]*)\}/g,
  )) {
    const subset = subsets.find((s) =>
      new RegExp(`^${name}-${s}-[a-z]+-(normal|italic)$`).test(label),
    );
    if (!subset) continue;
    const file = /url\(\.\/files\/([\w.-]+\.woff2)\)/.exec(body)[1];
    files.push(file);
    const decl = (prop) => new RegExp(`${prop}:\\s*([^;]+);`).exec(body)[1];
    rules.push(`/* ${label} */
@font-face {
  font-family: "${family}";
  font-style: ${decl("font-style")};
  font-display: swap;
  font-weight: ${decl("font-weight")};
  src: url("./${file}") format("woff2");
  unicode-range: ${decl("unicode-range")};
}`);
  }
  return { css: rules.join("\n\n"), files };
}

async function main(outDir = "src/fonts") {
  const modules = fileURLToPath(new URL("../node_modules/", import.meta.url));
  await mkdir(outDir, { recursive: true });
  const blocks = [
    "/* Generated by scripts/fonts.js from @fontsource-variable (SIL OFL 1.1, see OFL-*.txt). */",
  ];
  for (const font of FONTS) {
    const dir = join(modules, font.pkg);
    for (const css of font.css) {
      const { css: rules, files } = selectFaces(
        await readFile(join(dir, css), "utf8"),
        font,
      );
      blocks.push(rules);
      for (const file of files)
        await copyFile(join(dir, "files", file), join(outDir, file));
    }
    await copyFile(
      join(dir, "LICENSE"),
      join(outDir, `OFL-${font.pkg.split("/").pop()}.txt`),
    );
  }
  await writeFile(join(outDir, "fonts.css"), blocks.join("\n\n") + "\n");
  console.log(`fonts → ${outDir}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url))
  await main(process.argv[2]);
